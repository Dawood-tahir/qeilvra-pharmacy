import MedicinesPage from "@/app/(app)/medicines/page";
import { createRoot } from "react-dom/client";
import { Toaster } from "sonner";
import { MedicineForm } from "@/components/medicines/medicine-form";
import { RestockForm } from "@/components/medicines/restock-form";
import { PosWorkspace } from "@/components/pos/pos-workspace";
import { PurchaseForm } from "@/components/purchases/purchase-form";
import { AppShell } from "@/components/app-shell";
import DashboardPage from "@/app/(app)/dashboard/page";
import NewPurchasePage from "@/app/(app)/purchases/new/page";
import PurchaseDetailPage from "@/app/(app)/purchases/[id]/page";
import PurchasesPage from "@/app/(app)/purchases/page";
import SalesPage from "@/app/(app)/sales/page";
import SaleDetailPage from "@/app/(app)/sales/[id]/page";
import ReturnsPage from "@/app/(app)/returns/page";
import ExpensesPage from "@/app/(app)/expenses/page";
import SuppliersPage from "@/app/(app)/suppliers/page";
import ReportsPage from "@/app/(app)/reports/page";
import SettingsPage from "@/app/(app)/settings/page";
import UsersPage from "@/app/(app)/users/page";
import AlertsPage from "@/app/(app)/alerts/page";
import NotificationsPage from "@/app/(app)/notifications/page";
import StockPage from "@/app/(app)/stock/page";
import { suppliers, sale, purchase } from "./data";
import "@/app/globals.css";
const params = new URLSearchParams(location.search);
const searchParams = Promise.resolve(Object.fromEntries(params));
const routeFlows: Record<string, string> = { "/medicines": "inventory", "/medicines/new": "new", "/medicines/restock": "restock", "/pos": "pos", "/dashboard": "dashboard", "/sales": "sales", "/purchases": "purchases", "/purchases/new": "purchase", "/returns": "returns", "/suppliers": "suppliers", "/expenses": "expenses", "/reports": "reports", "/settings": "settings", "/users": "users", "/alerts": "alerts", "/notifications": "notifications", "/stock": "stock" };
const flow = routeFlows[location.pathname] ?? (location.pathname.startsWith("/sales/") ? "receipt" : location.pathname.startsWith("/purchases/") ? "purchase-detail" : params.get("flow"));
const role = params.get("role") === "salesperson" ? "salesperson" as const : "owner" as const;
let screen;
switch (flow) {
  case "inventory": screen = await MedicinesPage({ searchParams }); break;
  case "pos": screen = <PosWorkspace role={role} staffId="fixture" />; break;
  case "dashboard": screen = await DashboardPage({ searchParams }); break;
  case "purchase": screen = params.get("suppliers") === "none" ? <PurchaseForm suppliers={[]} /> : await NewPurchasePage(); break;
  case "purchase-detail": screen = await PurchaseDetailPage({ params: Promise.resolve({ id: purchase.id }) }); break;
  case "purchases": screen = await PurchasesPage(); break;
  case "receipt": screen = await SaleDetailPage({ params: Promise.resolve({ id: sale.id }), searchParams }); break;
  case "sales": screen = await SalesPage(); break;
  case "returns": screen = await ReturnsPage(); break;
  case "expenses": screen = await ExpensesPage({ searchParams }); break;
  case "suppliers": screen = await SuppliersPage({ searchParams }); break;
  case "reports": screen = await ReportsPage({ searchParams }); break;
  case "settings": screen = await SettingsPage(); break;
  case "users": screen = await UsersPage(); break;
  case "alerts": screen = await AlertsPage({ searchParams }); break;
  case "notifications": screen = await NotificationsPage(); break;
  case "stock": screen = await StockPage({ searchParams }); break;
  default: screen = <main className="mx-auto max-w-3xl p-4"><h1 className="mb-4 text-2xl font-extrabold">{flow === "restock" ? "Add More Stock" : "Add New Medicine"}</h1><div className="rounded-2xl border border-slate-200 bg-white p-4">{flow === "restock" ? <RestockForm suppliers={params.get("suppliers") === "none" ? [] : suppliers} /> : <MedicineForm />}</div></main>;
}
const content = params.has("shell") ? <AppShell staff={{ id: "fixture", fullName: "Test " + role, email: "fixture@example.test", role }}>{screen}</AppShell> : <><div className="border-b bg-[#071b45] p-4 font-bold text-white">Qeilvra <span className="text-xs font-normal text-blue-200">workflow test fixture</span></div>{screen}</>;
createRoot(document.getElementById("root")!).render(<>{content}<Toaster /></>);
